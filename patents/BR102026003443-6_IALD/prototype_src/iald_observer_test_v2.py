    def in_w(s, m): return results[s][m]['frac_in_window'] >= 0.5
    def cross_ok(s): return results[s]['cross']['frac_cross_formed'] >= 0.5

    # H1: Q, K, gate mostram quadratura (≥ 2/3 medições positivas)
    h1_per_set = {}
    for s in ['Q', 'K', 'gate']:
        votes = sum(in_w(s, m) for m in ['acf', 'fft', 'orbit'])
        h1_per_set[s] = {'votes': votes, 'pass': votes >= 2}
    h1 = all(h1_per_set[s]['pass'] for s in ['Q', 'K', 'gate'])

    # H0: GOE NÃO mostra quadratura
    h0 = sum(not in_w('GOE_null', m) for m in ['acf', 'fft', 'orbit']) >= 2

    # C1: embedding NÃO mostra quadratura
    c1 = sum(not in_w('embedding', m) for m in ['acf', 'fft', 'orbit']) >= 2

    # H2: Q, K, gate mostram cruz formada; GOE e embedding não
    h2_qkgate = all(cross_ok(s) for s in ['Q', 'K', 'gate'])
    h2_negative = (not cross_ok('GOE_null')) and (not cross_ok('embedding'))
    h2 = h2_qkgate and h2_negative

    # Veredicto
    if h1 and h0 and c1 and h2:
        verdict = "FIRST_LAW_CONFIRMED"
        meaning = ("Primeira Lei de Miguel confirmada: quadratura de paridade "
                   "(N≈14) e formação da cruz detectadas em Q,K,gate, "
                   "ausentes em embedding e GOE.")
    elif h1 and h0 and c1 and not h2:
        verdict = "QUADRATURE_ONLY"
        meaning = ("Quadratura confirmada (N≈14) mas cruz não formada. "
                   "Sistema oscila perpendicularmente mas sem fechar 360° "
                   "em quatro picos discretos. Operação parcial da Primeira Lei.")
    elif h1 and not (h0 and c1):
        verdict = "ARTIFACT"
        meaning = ("N≈14 aparece também em controles. Não é específico de "
                   "matrizes onde β_TGL opera.")
    elif not h1:
        verdict = "REFUTED"
        meaning = ("Quadratura N≈14 não detectada em Q, K, gate. "
                   "Hipótese refutada nos dados atuais.")
    else:
        verdict = "INCONCLUSIVE"
        meaning = "Resultado misto."

    return {
        'h1_per_set': h1_per_set, 'h1_overall': h1,
        'h0_overall': h0,
        'c1_overall': c1,
        'h2_qkgate': h2_qkgate, 'h2_negative_controls': h2_negative,
        'h2_overall': h2,
        'verdict': verdict,
        'meaning': meaning,
    }


