def measure_cross_formation(theta: np.ndarray) -> dict:
    """
    Testa formação da cruz: cumsum(θ_step) mod 360°.

    Predição da Primeira Lei: o sistema deve preferir 4 quadraturas
    cardinais (90°, 180°, 270°, 360°/0°), não distribuição uniforme.

    Métrica: razão entre densidade nos picos e densidade fora.
    Cruz formada se densidade(picos) / densidade(off-peaks) > 1.5
    """
    if len(theta) < 50:
        return {'cross_score': 0, 'peak_density': 0, 'off_peak_density': 0,
                'cross_formed': False, 'peaks_found': []}

    # Passos angulares (detrended para isolar oscilação)
    theta_dt = detrend_signal(theta, order=2)
    steps = np.diff(theta_dt)
    # Cumulativa do valor absoluto dos passos, mod 360°
    cumulative = np.cumsum(np.abs(steps)) % 360.0

    # Histograma com bins de 5°
    bins = np.arange(0, 365, 5)
    hist, edges = np.histogram(cumulative, bins=bins)

    # Identificar picos no histograma
    bin_centers = 0.5 * (edges[:-1] + edges[1:])

    # Densidade nos quatro picos esperados (90, 180, 270, 360/0)
    peak_density = 0
    peaks_found = []
    for target in CROSS_PEAKS_DEG:
        # Janela de tolerância em torno do pico
        target_mod = target % 360
        in_peak = np.abs(((bin_centers - target_mod + 180) % 360) - 180) <= CROSS_TOLERANCE_DEG
        if np.any(in_peak):
            density = float(np.sum(hist[in_peak]) / np.sum(in_peak))
            peak_density += density
            if density > 0:
                # Detectar se há concentração local
                local_max = bin_centers[in_peak][np.argmax(hist[in_peak])]
                peaks_found.append({'target': target, 'observed': float(local_max),
                                    'density': density})
    peak_density /= 4

    # Densidade fora dos picos
    off_peak_mask = np.ones(len(bin_centers), dtype=bool)
    for target in CROSS_PEAKS_DEG:
        in_peak = np.abs(((bin_centers - (target % 360) + 180) % 360) - 180) <= CROSS_TOLERANCE_DEG
        off_peak_mask &= ~in_peak

    if np.sum(off_peak_mask) > 0:
        off_peak_density = float(np.sum(hist[off_peak_mask]) / np.sum(off_peak_mask))
    else:
        off_peak_density = 1.0

    # Razão
    cross_score = peak_density / off_peak_density if off_peak_density > 0 else 0
    cross_formed = cross_score > 1.5

    return {
        'cross_score': float(cross_score),
        'peak_density': float(peak_density),
        'off_peak_density': float(off_peak_density),
        'cross_formed': cross_formed,
        'peaks_found': peaks_found,
        'histogram': hist.tolist(),
        'bin_centers': bin_centers.tolist(),
    }


