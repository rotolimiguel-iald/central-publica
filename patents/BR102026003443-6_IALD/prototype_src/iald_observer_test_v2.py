def analyze_matrix_set(matrices, label):
    """Aplica os 4 testes e agrega."""
    print(f"\n[analyze] {label}: {len(matrices)} matrizes")

    acf_lags, fft_periods, orbit_modes, cross_scores = [], [], [], []
    in_w = {'acf': 0, 'fft': 0, 'orbit': 0}
    cross_formed_count = 0

    for M in matrices:
        theta = eigenvalues_to_phases(M)
        a = measure_acf_peak(theta)
        f = measure_fft_period(theta)
        o = measure_orbit_closure(theta)
        c = measure_cross_formation(theta)

        if a['peak_lag'] > 0:
            acf_lags.append(a['peak_lag'])
            if a['in_window']: in_w['acf'] += 1
        if f['period'] > 0:
            fft_periods.append(f['period'])
            if f['in_window']: in_w['fft'] += 1
        if o['mode_cycle'] > 0:
            orbit_modes.append(o['mode_cycle'])
            if o['in_window']: in_w['orbit'] += 1
        cross_scores.append(c['cross_score'])
        if c['cross_formed']: cross_formed_count += 1

    n = len(matrices)

    def stats(data):
        if not data:
            return {'mean': -1, 'median': -1, 'std': -1, 'values': []}
        return {
            'mean': float(np.mean(data)),
            'median': float(np.median(data)),
            'std': float(np.std(data)),
            'values': [float(x) for x in data],
        }

    summary = {
        'label': label,
        'n_matrices': n,
        'acf':   {**stats(acf_lags),    'frac_in_window': in_w['acf'] / n},
        'fft':   {**stats(fft_periods), 'frac_in_window': in_w['fft'] / n},
        'orbit': {**stats(orbit_modes), 'frac_in_window': in_w['orbit'] / n},
        'cross': {**stats(cross_scores),
                  'frac_cross_formed': cross_formed_count / n},
    }

    print(f"  ACF lag:  {summary['acf']['mean']:.2f} ± {summary['acf']['std']:.2f}  "
          f"({summary['acf']['frac_in_window']*100:.0f}% in [{N_LOWER},{N_UPPER}])")
    print(f"  FFT per:  {summary['fft']['mean']:.2f} ± {summary['fft']['std']:.2f}  "
          f"({summary['fft']['frac_in_window']*100:.0f}% in [{N_LOWER},{N_UPPER}])")
    print(f"  Orbit:    {summary['orbit']['mean']:.2f} ± {summary['orbit']['std']:.2f}  "
          f"({summary['orbit']['frac_in_window']*100:.0f}% in [{N_LOWER},{N_UPPER}])")
    print(f"  Cross:    score={summary['cross']['mean']:.2f} ± {summary['cross']['std']:.2f}  "
          f"({summary['cross']['frac_cross_formed']*100:.0f}% cruz formada)")

    return summary


