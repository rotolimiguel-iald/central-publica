            n = EIGS_PER_LAYER
            # Gaps com modulação senoidal de período 14.29
            mean_gap = 0.001
            gap_modulation = 0.0005 * np.sin(2 * np.pi * np.arange(n) / N_QUADRATURE_PREDICTED)
            gaps = mean_gap + gap_modulation
            gaps = np.maximum(gaps, 1e-6)  # garantir positivos
