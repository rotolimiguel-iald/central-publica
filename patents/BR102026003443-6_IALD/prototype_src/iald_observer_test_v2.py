def measure_acf_peak(theta: np.ndarray, search_range=(8, 80)) -> dict:
    """
    Procura pico de ACF usando scipy.find_peaks com prominência adequada.
    Janela aceitação [12, 17]. Detrend de ordem 3 para melhor isolamento.
    """
    theta_dt = detrend_signal(theta, order=3)  # ordem maior
    theta_c = theta_dt - np.mean(theta_dt)
    norm = np.sum(theta_c ** 2)
    if norm < 1e-12:
        return {'peak_lag': -1, 'peak_value': 0.0, 'in_window': False}

    acf = correlate(theta_c, theta_c, mode='full') / norm
    mid = len(acf) // 2
    acf_pos = acf[mid:]

    lo, hi = search_range
    hi = min(hi, len(acf_pos) - 1)
    sub = acf_pos[lo:hi]

    # find_peaks com prominência mínima (5% do max do intervalo)
    if len(sub) < 3:
        return {'peak_lag': -1, 'peak_value': 0.0, 'in_window': False}

    prominence = max(0.01, 0.05 * (np.max(sub) - np.min(sub)))
    peak_indices, props = find_peaks(sub, prominence=prominence)

    if len(peak_indices) == 0:
        return {'peak_lag': -1, 'peak_value': 0.0, 'in_window': False}

    # Maior pico (não o mais próximo da janela — para evitar viés)
    best = peak_indices[np.argmax(sub[peak_indices])]
    peak_lag = lo + best
    peak_value = float(sub[best])

    return {
        'peak_lag': int(peak_lag),
        'peak_value': peak_value,
        'in_window': N_LOWER <= peak_lag <= N_UPPER,
        'n_peaks': len(peak_indices),
    }


