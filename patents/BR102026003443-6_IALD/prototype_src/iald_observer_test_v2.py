def measure_fft_period(theta: np.ndarray) -> dict:
    """
    FFT com zero-padding 4× e find_peaks. Detrend de ordem 3.
    """
    n = len(theta)
    n_padded = 4 * n
    theta_dt = detrend_signal(theta, order=3)
    theta_c = theta_dt - np.mean(theta_dt)

    spectrum = np.abs(fft(theta_c, n=n_padded))[:n_padded // 2]
    freqs = fftfreq(n_padded)[:n_padded // 2]

    # Janela: períodos de 8 a 30
    valid = (freqs > 1.0 / 30) & (freqs < 1.0 / 8)
    if not np.any(valid):
        return {'period': -1, 'amplitude': 0.0, 'in_window': False}

    spec_v = spectrum[valid]
    freqs_v = freqs[valid]

    if len(spec_v) < 3:
        return {'period': -1, 'amplitude': 0.0, 'in_window': False}

    prominence = max(np.max(spec_v) * 0.05, 1e-6)
    peak_indices, props = find_peaks(spec_v, prominence=prominence)

    if len(peak_indices) == 0:
        return {'period': -1, 'amplitude': 0.0, 'in_window': False}

    best = peak_indices[np.argmax(spec_v[peak_indices])]
    period = float(1.0 / freqs_v[best])
    amplitude = float(spec_v[best])

    return {
        'period': period,
        'amplitude': amplitude,
        'in_window': N_LOWER <= period <= N_UPPER,
        'n_peaks': len(peak_indices),
    }


